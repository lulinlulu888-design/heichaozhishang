"""Generate UE cue data from the hash-pinned original Elsa event track."""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'analysis/battle-visual/skill-animation/ailisha.ags'
OUTPUT = ROOT / 'clients/unreal5 5.8/Source/Hczs/Private/HczsElsaUltimateEvents.inl'
SHA = '12702cdbf02201e0637ca1410db6abe9787c29a05ea1514d4c5f5b9a7318e729'


def generate():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA:
        raise ValueError('Original event track identity changed')
    track = ET.fromstring(raw).find('.//EventTrack_crit_4')
    if track is None:
        raise ValueError('Original ultimate track missing')
    events = sorted(track.findall('Event'), key=lambda e: float(e.attrib['TimeRatio']))
    names = [e.attrib['Name'] for e in events]
    if len(set(names)) != len(names) or names.count('video') != 1:
        raise ValueError('Unexpected cue identities')
    rows = []
    for event in events:
        name, ratio = event.attrib['Name'], event.attrib['TimeRatio']
        if not name.replace('_', '').isalnum() or not 0 <= float(ratio) <= 1:
            raise ValueError('Invalid source cue')
        rows.append('    {TEXT("%s"), %sf},' % (name, ratio))
    return '// Generated by tools/prepare_ultimate_event_track.py; do not hand-edit.\n' + \
        '// Original ailisha.ags SHA256: ' + SHA + '\n' + \
        'constexpr FSourceUltimateCue ElsaSourceCues[] = {\n' + '\n'.join(rows) + '\n};\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--verify-playback', type=Path)
    args = parser.parse_args()
    content = generate()
    if args.check:
        if OUTPUT.read_text('utf8') != content:
            raise ValueError('UE event data differs from the original track')
    else:
        OUTPUT.write_text(content, encoding='utf8', newline='\n')
    if args.verify_playback:
        report = json.loads(args.verify_playback.read_text('utf8'))
        expected = sorted(ET.fromstring(SOURCE.read_bytes()).find('.//EventTrack_crit_4').findall('Event'),
                          key=lambda e: float(e.attrib['TimeRatio']))
        actual = [e for e in report['events'] if e['name'] != 'video-complete']
        if not report['passed'] or len(actual) != len(expected):
            raise ValueError('Playback failed or source event count differs')
        for event, recorded in zip(expected, actual):
            if event.attrib['Name'] != recorded['name'] or abs(float(event.attrib['TimeRatio']) * 7.2 - recorded['sourcePosition']) > .00001:
                raise ValueError('Runtime source event order or timing differs')
        video_index = next(i for i, e in enumerate(report['events']) if e['name'] == 'video')
        if report['events'][video_index + 1]['name'] != 'video-complete':
            raise ValueError('Source cues advanced while video was playing')
        print(f'Actual UE playback matched all {len(expected)} original cues; no source cue leaked into video pause')
    print(f'Original event track verified: {OUTPUT}')
